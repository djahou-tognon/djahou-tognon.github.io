function t(path) {
  const lang = getLang();
  const value = path.split(".").reduce((node, key) => node?.[key], UI[lang]);
  return value == null ? path : value;
}

function getLang() {
  const stored = localStorage.getItem("folio-lang");
  const fallback = typeof SITE !== "undefined" ? SITE.display?.language : "en";
  const lang = stored || fallback || "en";
  return UI[lang] ? lang : "en";
}
